// Copies the exact Lucide icon geometry the tailoring wizard uses into
// icons.js, so the video draws the same glyphs as the app (lucide-react 0.446).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '../../node_modules/lucide-react/dist/esm/icons');
const names = [
  'upload', 'file-text', 'chevron-left', 'chevron-right', 'chevron-down', 'loader-2',
  'target', 'lightbulb', 'check-circle', 'rotate-ccw', 'download', 'palette',
  'file-edit', 'sun', 'check-check', 'external-link',
  // features.html
  'briefcase', 'building-2', 'map-pin', 'clock', 'arrow-up-right', 'banknote', 'share-2',
  'layout-dashboard', 'plus', 'newspaper', 'user-circle', 'credit-card', 'star', 'grip-vertical',
  'maximize', 'zoom-in', 'zoom-out', 'save', 'x', 'sparkles', 'mail', 'lock', 'clipboard',
  'message-square', 'trending-up', 'search', 'bell', 'check', 'handshake',
];

function nodesFor(name) {
  const src = readFileSync(join(dir, `${name}.js`), 'utf8');
  const body = src.match(/createLucideIcon\([^,]+,\s*(\[[\s\S]*?\])\);/);
  if (body) return Function(`return ${body[1]}`)();
  // Aliases (check-circle -> circle-check-big) just re-export another file.
  const alias = src.match(/from '\.\/([\w-]+)\.js'/);
  return nodesFor(alias[1]);
}

const out = {};
for (const n of names) {
  out[n] = nodesFor(n)
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ');
      return `<${tag} ${a}/>`;
    })
    .join('');
}
writeFileSync(join(here, 'icons.js'), `// Generated by extract-icons.mjs — do not edit.\nwindow.ICONS = ${JSON.stringify(out, null, 2)};\n`);
console.log('wrote', Object.keys(out).length, 'icons');
